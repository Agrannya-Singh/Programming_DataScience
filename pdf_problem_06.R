# Function Definition
calculate _bmi <- function ( height , weight) {
# BMI Fo rmula: weight ( kg) / [ height ( m)]^2
bmi <- weight / ( height ^ 2)
return ( bmi)
}
# --- Driver Code / Test Cases --# Note: Inputs passed as ( height , weight) per problem statement
bmi1 <- calculate_bmi (1.75 , 70)
bmi2 <- calculate_bmi (1.60 , 60)
bmi3 <- calculate_bmi (1.80 , 85)
bmi4 <- calculate_bmi (1.65 , 50)
# Printing Results
cat(" BMI for height 1.75 m and weight 70 kg:", bmi1 , "\n")
cat(" BMI for height 1.60 m and weight 60 kg:", bmi2 , "\n")
cat(" BMI for height 1.80 m and weight 85 kg:", bmi3 , "\n")
cat(" BMI for height 1.65 m and weight 50 kg:", bmi4 , "\n")
