# Function Definition
make_full_ name <- function ( first_name , last_ name ) {
# paste() joins strings with a space separator by default
full_ name
<paste ( first_name ,
last_ name )
return ( full_ name )
}
# --- Driver Code / Test Cases --name1 <- make_full_ name (" John ", " Doe ")
name2 <- make_full_ name (" Alice ", " Smith ")
name3 <- make_full_ name (" Rahul", " Sharma ")
name4 <- make_full_ name (" E mily ", " Blunt")
# Printing Results
cat(" Full name for John and Doe :", name1 , "\n")
cat(" Full name for Alice and Smith :", name2 , "\n")
cat(" Full name for Rahul and Sharma :", name3 , "\n")
cat(" Full name for Emily and Blunt:", name4 , "\n")
